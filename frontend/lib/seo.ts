import type { Metadata } from "next";

/**
 * Single source of truth for anything that ends up in a <head> tag, a
 * sitemap entry or a robots rule. Keeping it here means the canonical
 * host, the product name and the marketing copy can never drift apart
 * between the layout, the sitemap and the structured data.
 */

/**
 * Public origin the site is served from, with no trailing slash.
 *
 * Must be an absolute URL: `metadataBase`, canonicals, the sitemap and
 * JSON-LD all resolve against it, and relative values would silently
 * produce broken tags. Set NEXT_PUBLIC_SITE_URL at build time — it is
 * inlined into the client bundle, so changing it needs a rebuild.
 */
export const SITE_URL = (process.env.NEXT_PUBLIC_SITE_URL ?? "https://localhost")
  .replace(/\/+$/, "");

