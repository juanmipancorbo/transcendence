/** Absolute URL for `path`, which should start with a slash. */
export function absoluteUrl(path = "/"): string {
  return `${SITE_URL}${path.startsWith("/") ? path : `/${path}`}`;
}

export const OG_IMAGE_ALT = `${SITE_NAME} — play Reversi online against real opponents`;

/**
 * The social card, generated by app/opengraph-image.tsx. Referenced by an
 * explicit path rather than left to Next's file convention — see
 * `pageMetadata` for why that matters.
 */
export const OG_IMAGE = {
  url: "/opengraph-image",
  width: 1200,
  height: 630,
  alt: OG_IMAGE_ALT,
  type: "image/png",
} as const;

/**
 * Builds a complete Metadata object for one public route.
 *
 * Next.js does **not** deep-merge `openGraph` and `twitter`: a child route
 * that sets either one replaces the parent's version entirely, and that
 * also discards the image Next would otherwise attach from the
 * opengraph-image file convention. Overriding just a title in a child is
 * therefore enough to silently strip `og:image` and downgrade
 * `twitter:card` back to the small `summary` layout.
 *
 * Every public route goes through this helper so those fields are always
 * emitted in full.
 */
export function pageMetadata({
  title,
  description,
  path,
  socialTitle,
  socialDescription,
  robots,
}: {
  title: string;
  description: string;
  /** Route path, used for the canonical and `og:url`. */
  path: string;
  /** Shorter title for social cards; defaults to `title`. */
  socialTitle?: string;
  /** Shorter description for social cards; defaults to `description`. */
  socialDescription?: string;
  robots?: Metadata["robots"];
}): Metadata {
  const ogTitle = socialTitle ?? title;
  const ogDescription = socialDescription ?? description;

  return {
    title,
    description,
    alternates: { canonical: path },
    openGraph: {
      type: "website",
      siteName: SITE_NAME,
      locale: SITE_LOCALE,
      url: path,
      title: ogTitle,
      description: ogDescription,
      images: [OG_IMAGE],
    },
    twitter: {
      card: "summary_large_image",
      title: ogTitle,
      description: ogDescription,
      images: [OG_IMAGE],
    },
    ...(robots ? { robots } : {}),
  };
}

